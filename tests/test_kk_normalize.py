import pytest

from audio8_tts_kk_normalize import cardinal, normalize_kk, ordinal


@pytest.mark.parametrize(
    ("value", "expected"),
    [
        (0, "нөл"),
        (7, "жеті"),
        (15, "он бес"),
        (40, "қырық"),
        (100, "жүз"),
        (245, "екі жүз қырық бес"),
        (1000, "мың"),
        (2019, "екі мың он тоғыз"),
        (1991, "мың тоғыз жүз тоқсан бір"),
        (25000, "жиырма бес мың"),
        (1_500_000, "бір миллион бес жүз мың"),
        (3_000_000_000, "үш миллиард"),
    ],
)
def test_cardinal(value: int, expected: str) -> None:
    assert cardinal(value) == expected


@pytest.mark.parametrize(
    ("value", "expected"),
    [
        (1, "бірінші"),
        (2, "екінші"),
        (6, "алтыншы"),
        (9, "тоғызыншы"),
        (10, "оныншы"),
        (20, "жиырмасыншы"),
        (40, "қырқыншы"),
        (50, "елуінші"),
        (100, "жүзінші"),
        (2019, "екі мың он тоғызыншы"),
        (2020, "екі мың жиырмасыншы"),
    ],
)
def test_ordinal(value: int, expected: str) -> None:
    assert ordinal(value) == expected


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("2019 жылы грант алды.", "екі мың он тоғызыншы жылы грант алды."),
        ("2019-жылы", "екі мың он тоғызыншы жылы"),
        ("Ауданы 2,5 мың шаршы метр.", "Ауданы екі бүтін оннан бес мың шаршы метр."),
        ("9.5 пайыз", "тоғыз бүтін оннан бес пайыз"),
        ("3,25", "үш бүтін жүзден жиырма бес"),
        ("Инфляция 8%.", "Инфляция сегіз пайыз."),
        ("5-сынып", "бесінші сынып"),
        ("1990-шы жылдары", "мың тоғыз жүз тоқсаныншы жылдары"),
        ("5-ке бөлінеді", "беске бөлінеді"),
        ("10-нан астам", "оннан астам"),
        ("15 наурызда", "он бесінші наурызда"),
        ("16.12.1991", "мың тоғыз жүз тоқсан бірінші жылғы он алтыншы желтоқсан"),
        ("Сағат 14:30-да", "Сағат он төрт отызда"),
        ("XXI ғасыр", "жиырма бірінші ғасыр"),
        ("2019-2020 жылдары", "екі мың он тоғызыншы-екі мың жиырмасыншы жылдары"),
        ("1 500 000 теңге", "бір миллион бес жүз мың теңге"),
        ("ҚР Президенті", "Қазақстан Республикасы Президенті"),
        ("5 млн теңге", "бес миллион теңге"),
        ("кітаптар, т.б.", "кітаптар, тағы басқа"),
        ("№3 мектеп", "нөмір үш мектеп"),
    ],
)
def test_normalize_kk(text: str, expected: str) -> None:
    assert normalize_kk(text) == expected


def test_latin_lookalikes_are_repaired_only_in_cyrillic_words() -> None:
    assert normalize_kk("мəжбүр") == "мәжбүр"
    assert normalize_kk("Алмaты") == "Алматы"  # Latin "a"
    assert normalize_kk("Coca-Cola") == "Coca-Cola"


def test_plain_text_is_unchanged() -> None:
    text = "Бізде отандық және халықаралық тәжірибеге негізделген заңнамалық база жасалды."
    assert normalize_kk(text) == text


def test_decomposed_short_i_is_composed() -> None:
    assert normalize_kk("й") == "й"
